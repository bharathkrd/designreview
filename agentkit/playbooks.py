"""
Playbooks: one file per use case, and a register of the numbers the rules use.

A playbook is a markdown file. Its head is TOML between two `+++` lines (what code reads);
its body is the procedure a person reads: when it runs, what it reads, what it checks, how
the answer reads, and its limits.

    +++
    id = "pb-01"
    title = "..."
    status = "live"              # live | blocked | spec
    plan = "..."                 # live / blocked: the plan its questions route to
    questions = ["..."]          # example questions; each must route to `plan`
    tools = ["Entity.list"]      # seat tools it reads or writes
    missing_tools = []           # blocked: tools absent from every seat catalogue
    tasks = ["t01_..."]          # tasks that exercise it
    triggers = ["on_request"]    # on_request | scheduled:<cadence> | event:<name>
    writes = false
    blocked_by = ""              # blocked: why, in one sentence
    +++

Status is a claim the check below proves against the files:
  live     the plan exists, its tools are in every seat catalogue, its questions route to it
  blocked  the request routes to `plan` (a refusal); `blocked_by` says why; any
           `missing_tools` are absent from every catalogue
  spec     designed, not built: every tool it would use is offered, and its questions route
           to the decline plan today (the agent says no rather than guess)

The body is documentation. Control flow stays in the plans: no playbook text reaches a
planner or adds a tool.

Constants (constants.toml): one table per number a rule uses, naming where the code reads
it, the unit, the source and the date a person last checked the source:

    [name]
    value = 0.25
    unit = "..."
    where = "config/project.toml#key.path"      # a TOML file and a dotted key
          | "package.module:NAME"                # a module attribute
          | "package.module:Callable(param)"     # a parameter's default value
    source = "..."
    verified = "2026-10-19"                      # "" = not checked yet

check_constants() reads each `where` and reports any value that differs from the register.
"""

from __future__ import annotations

import importlib
import inspect
import re
import tomllib
from pathlib import Path
from typing import Any, Dict, Iterable, List, Literal, Mapping, Sequence

from pydantic import ValidationError

from agentkit.agents.router import DECLINE_PLAN, RuleRouter
from agentkit.config import PROJECT_ROOT, ConfigError, _Strict, read_config, validation_message

FENCE = "+++"
STATUSES = ("live", "blocked", "spec")
TRIGGER = re.compile(r"^(on_request|scheduled:[a-z_]+|event:[A-Za-z0-9_.]+)$")
INDEX_START = "<!-- playbook index: start (generated by scripts/playbooks_check.py --write) -->"
INDEX_END = "<!-- playbook index: end -->"


class Playbook(_Strict):
    id: str
    title: str
    status: Literal["live", "blocked", "spec"]
    plan: str = ""
    questions: List[str]
    tools: List[str] = []
    missing_tools: List[str] = []
    tasks: List[str] = []
    triggers: List[str] = ["on_request"]
    writes: bool = False
    blocked_by: str = ""
    source: str = ""
    body: str = ""


class Constant(_Strict):
    value: Any
    unit: str
    where: str
    source: str
    verified: str = ""


def split_front_matter(text: str) -> tuple[Dict[str, Any], str]:
    if not text.startswith(FENCE):
        return {}, text
    _, head, body = text.split(FENCE, 2)
    return tomllib.loads(head), body.strip()


def load_playbooks(directory: Path) -> List[Playbook]:
    """Every playbook in `directory` (files with a front-matter head), sorted by id."""
    books = []
    for path in sorted(Path(directory).glob("*.md")):
        try:
            head, body = split_front_matter(path.read_text(encoding="utf-8"))
        except tomllib.TOMLDecodeError as e:
            raise ConfigError(f"{path}: {e}") from None
        if not head:
            continue
        try:
            books.append(Playbook.model_validate({**head, "source": path.name, "body": body}))
        except ValidationError as e:
            raise ConfigError(validation_message(e, str(path))) from None
    return sorted(books, key=lambda b: b.id)


def routed_plan(router: RuleRouter, question: str) -> str:
    """The plan a question routes to, by its words alone (record resolution not attempted)."""
    probe = RuleRouter(router.routes, lambda client, prompt, needs: {n: "<resolved>" for n in needs})
    return probe.route(question).plan


def check_playbooks(books: Sequence[Playbook], *, plans: Iterable[str], tasks: Mapping[str, Mapping[str, Any]],
                    catalogs: Mapping[str, Iterable[str]], router: RuleRouter) -> List[str]:
    """Every way a playbook's status, plan, tools, questions or tasks disagree with the files.

    plans     names of the plans the pack has
    tasks     task id -> task file contents (needs `plan` and `prompt`)
    catalogs  seat name -> tool names that seat offers (each captured tools/list)
    """
    plans = set(plans)
    catalogs = {k: set(v) for k, v in catalogs.items()}
    problems: List[str] = []
    seen: Dict[str, str] = {}
    claimed: Dict[str, str] = {}

    def offered_everywhere(tool: str) -> bool:
        return all(tool in tools for tools in catalogs.values())

    for b in books:
        where = f"{b.source} ({b.id})"
        if b.id in seen:
            problems.append(f"{where}: id also used by {seen[b.id]}")
        seen[b.id] = b.source
        for t in b.triggers:
            if not TRIGGER.match(t):
                problems.append(f"{where}: trigger {t!r} is not on_request, scheduled:<cadence> or event:<name>")
        expected = DECLINE_PLAN if b.status == "spec" else b.plan
        if b.status != "spec" and b.plan not in plans:
            problems.append(f"{where}: plan {b.plan!r} is not in the pack's plans")
        if b.status == "spec" and b.plan:
            problems.append(f"{where}: a spec playbook has no plan yet (found {b.plan!r})")
        if b.status == "blocked" and not b.blocked_by.strip():
            problems.append(f"{where}: blocked, but blocked_by does not say why")
        for tool in b.tools:
            if not offered_everywhere(tool):
                problems.append(f"{where}: tool {tool} is not offered to every seat"
                                + (" (move it to missing_tools)" if b.status == "blocked" else ""))
        for tool in b.missing_tools:
            offered = sorted(seat for seat, tools in catalogs.items() if tool in tools)
            if b.status != "blocked":
                problems.append(f"{where}: missing_tools is only for blocked playbooks")
            elif offered:
                problems.append(f"{where}: {tool} is listed missing but offered to {', '.join(offered)}")
        if not b.questions:
            problems.append(f"{where}: no example question")
        for q in b.questions:
            got = routed_plan(router, q)
            if got != expected:
                problems.append(f"{where}: question {q!r} routes to {got}, expected {expected}")
        for tid in b.tasks:
            if tid in claimed:
                problems.append(f"{where}: task {tid} is also claimed by {claimed[tid]}")
            claimed[tid] = b.id
            task = tasks.get(tid)
            if task is None:
                problems.append(f"{where}: task {tid} does not exist")
                continue
            if task.get("plan") not in ("route", b.plan):
                problems.append(f"{where}: task {tid} runs plan {task.get('plan')!r}, not {b.plan!r}")
            got = routed_plan(router, task.get("prompt") or "")
            if got != b.plan:
                problems.append(f"{where}: task {tid}'s question routes to {got}, not {b.plan}")

    for tid in sorted(set(tasks) - set(claimed)):
        problems.append(f"task {tid} belongs to no playbook")
    covered = {b.plan for b in books if b.status != "spec"} | {DECLINE_PLAN}
    for plan in sorted(plans - covered):
        problems.append(f"plan {plan} belongs to no playbook")
    return problems


STATUS_MARK = {"live": "live", "blocked": "blocked", "spec": "spec only"}


def index_table(books: Sequence[Playbook]) -> str:
    """The markdown index of the playbooks (the README section between the index markers)."""
    counts = {s: sum(b.status == s for b in books) for s in STATUSES}
    lines = [f"**{len(books)} playbooks:** {counts['live']} live, {counts['blocked']} blocked, "
             f"{counts['spec']} spec only.", "",
             "| Id | Title | Status | Plan | Triggers | Writes | Tasks |",
             "|---|---|---|---|---|---|---|"]
    for b in books:
        lines.append(f"| [{b.id}]({b.source}) | {b.title} | {STATUS_MARK[b.status]} | "
                     f"{'`' + b.plan + '`' if b.plan else '—'} | {' · '.join(b.triggers)} | "
                     f"{'yes' if b.writes else 'no'} | {', '.join(b.tasks) or '—'} |")
    return "\n".join(lines)


def with_index(readme: str, books: Sequence[Playbook]) -> str:
    """`readme` with the section between INDEX_START and INDEX_END replaced by index_table()."""
    start, end = readme.find(INDEX_START), readme.find(INDEX_END)
    if start < 0 or end < start:
        raise ConfigError("README has no playbook index markers")
    return readme[:start + len(INDEX_START)] + "\n" + index_table(books) + "\n" + readme[end:]


# ---------------------------------------------------------------- constants


def load_constants(path: Path) -> Dict[str, Constant]:
    out = {}
    for name, entry in read_config(path).items():
        try:
            out[name] = Constant.model_validate(entry)
        except ValidationError as e:
            raise ConfigError(validation_message(e, f"{path} [{name}]")) from None
    return out


_PARAM = re.compile(r"^(?P<obj>[\w.]+)\((?P<param>\w+)\)$")


def read_where(where: str, root: Path = PROJECT_ROOT) -> Any:
    """The value a `where` reference points at (see the module docstring)."""
    if "#" in where:
        file, key = where.split("#", 1)
        value: Any = read_config(root / file)
        for part in key.split("."):
            value = value[part]
        return value
    module, _, attr = where.partition(":")
    obj: Any = importlib.import_module(module)
    m = _PARAM.match(attr)
    for part in (m.group("obj") if m else attr).split("."):
        obj = getattr(obj, part)
    if m:
        return inspect.signature(obj).parameters[m.group("param")].default
    return obj


def _same(a: Any, b: Any) -> bool:
    if isinstance(b, (set, frozenset, tuple, list)) and isinstance(a, list):
        return sorted(map(str, a)) == sorted(map(str, b))
    return a == b


def check_constants(constants: Mapping[str, Constant], root: Path = PROJECT_ROOT) -> List[str]:
    problems = []
    for name, c in constants.items():
        try:
            actual = read_where(c.where, root)
        except (ConfigError, KeyError, AttributeError, ImportError, ValueError) as e:
            problems.append(f"{name}: cannot read {c.where}: {e}")
            continue
        if not _same(c.value, actual):
            problems.append(f"{name}: register says {c.value!r}, {c.where} has {actual!r}")
    return problems


def unverified(constants: Mapping[str, Constant]) -> List[str]:
    return sorted(name for name, c in constants.items() if not c.verified)


